// Helper function to resolve place image with fuzzy/case-insensitive matching
export function getPlaceImage(placeTitle: string): string {
  if (!placeTitle) return "";

  // 1. Direct exact key match
  if (placeImageMap[placeTitle]) return placeImageMap[placeTitle];

  const normTarget = placeTitle.toLowerCase().replace(/[^a-z0-9]/g, "");
  if (!normTarget) return "";

  // 2. Exact normalized match
  for (const [key, value] of Object.entries(placeImageMap)) {
    const normKey = key.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (normKey === normTarget) {
      return value;
    }
  }

  // 3. Substring match for longer keys (minimum 4 characters)
  if (normTarget.length >= 4) {
    for (const [key, value] of Object.entries(placeImageMap)) {
      const normKey = key.toLowerCase().replace(/[^a-z0-9]/g, "");
      if (normKey.length >= 4 && (normKey.includes(normTarget) || normTarget.includes(normKey))) {
        return value;
      }
    }
  }

  return "";
}
